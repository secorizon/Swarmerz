DEFAULT_THEME = "mono"


def theme_names() -> tuple[str, ...]:
    return tuple(_THEMES)


def initial_theme_name() -> str:
    requested = os.environ.get("SWARMERZ_THEME", "").strip().lower()
    return requested if requested in _THEMES else DEFAULT_THEME


def style_for(name: str) -> Style:
    return Style.from_dict(_THEMES.get(name, _THEMES[DEFAULT_THEME]))


def next_theme_name(name: str) -> str:
    names = theme_names()
    try:
        index = names.index(name)
    except ValueError:
        return DEFAULT_THEME
    return names[(index + 1) % len(names)]
